def locate(L, j):
    """按起始锚点唯一定位，区间长度沿用原始行号差 —— 这样上一轮改过的文件也不会错位。"""
    idx = [i for i, l in enumerate(L) if j["m1"] in l]
    assert len(idx) == 1, "%s 起始锚点命中 %d 次: %r" % (j["f"], len(idx), j["m1"])
    a = idx[0] + 1
    b = a + (j["b"] - j["a"])
    assert j["m2"] in L[b - 1], "%s 结束锚点不匹配: %r" % (j["f"], L[b - 1])
    return a, b


def main():
    changed_any = False
    order = []
    for j in JOBS:
        if j["f"] not in order:
            order.append(j["f"])
    # 同一份文件里按行号从下往上改：先动的行在后面，前面的行号才不会被顶掉。
    plan = []
    for f in order:
        for j in sorted([x for x in JOBS if x["f"] == f], key=lambda x: -x["a"]):
            plan.append(j)

    for j in plan:
        raw = open(j["f"], "rb").read()
        assert raw[:3] != b"\xef\xbb\xbf", "%s 不该有 BOM" % j["f"]
        text = raw.decode(j["enc"])
        assert "\r\n" in text and text.count("\n") == text.count("\r\n"), "%s 不是纯 CRLF" % j["f"]
        L = text.split("\r\n")

        if j["new"] == [""]:
            # 删除型：判据 = 两行都不在了
            if not any(j["m1"] in l for l in L) and not any(j["m2"] in l for l in L):
                print("SKIP  %-16s 删除项已经不在了" % j["f"])
                continue
            a, b = locate(L, j)
            del L[a - 1:b]
            out = "\r\n".join(L).encode(j["enc"])
        else:
            if j["done"] in "\r\n".join(L):
                print("SKIP  %-16s 已经是新内容" % j["f"])
                continue
            a, b = locate(L, j)
            L[a - 1:b] = j["new"]
            out = "\r\n".join(L).encode(j["enc"])

        with open(j["f"], "wb") as fp:
            fp.write(out)
        changed_any = True
        print("OK    %-16s 行 %d-%d -> %d 行，文件 %d -> %d 字节"
              % (j["f"], j["a"], j["b"], len(j["new"]) if j["new"] != [""] else 0,
                 len(raw), len(out)))

    print()
    if not changed_any:
        print("四份文档的风扇功率/电量段落都已经是新口径了，跳过。")
    # 收尾复验
    print("-" * 60)
    for f, enc in [(USAGE, "gbk"), ("首次使用.txt", "gbk"), (MD, "utf-8"), (HTML, "utf-8")]:
        raw = open(f, "rb").read()
        t = raw.decode(enc)
        crlf = t.count("\r\n")
        lf_only = t.count("\n") - crlf
        print("%-16s %5d 行 %6d 字节  enc=%s  BOM=%s  裸LF=%d"
              % (f, len(t.split("\r\n")), len(raw), enc, raw[:3] == b"\xef\xbb\xbf", lf_only))
    print("-" * 60)
    bad = 0
    for f, enc in [(USAGE, "gbk"), (MD, "utf-8"), (HTML, "utf-8")]:
        t = open(f, encoding=enc, newline="").read()
        for kw in ("按「额定功率 × 档位比例 × 自然风系数」算出来的",
                   "三格用电量是对它做时间积分",
                   "推算功率曲线：区间按钮",
                   "额定功率（1~100 W）",
                   "data\\fan-energy.json",
                   "data\\fan-history-min.jsonl"):
            if kw in t:
                print("!! 残留: %s %s" % (f, kw))
                bad += 1
    print("残留检查：%s" % ("通过" if bad == 0 else "%d 处未清" % bad))


if __name__ == "__main__":
    main()
