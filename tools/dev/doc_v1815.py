"""v1.8.15 文档更新：温湿度曲线（去掉橙色阴影带 / 独立平滑开关 / 卡片可收起）。

一次跑完，幂等：找不到锚点就报错并保持原文件不动。
用法: python tools/dev/doc_v1815.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CRLF = "\r\n"
changed = 0


def load(name, enc):
    raw = (ROOT / name).read_bytes()
    s = raw.decode(enc)
    # 统一成 LF 处理，最后写回时再按文件约定转回去
    return s.replace(CRLF, "\n").replace("\r", "\n")


def save(name, s, enc, crlf=True):
    txt = s.replace("\n", CRLF) if crlf else s
    (ROOT / name).write_bytes(txt.encode(enc))


def sub1(s, old, new, tag):
    if s.count(old) != 1:
        print("  !! %s 命中 %d 次，跳过" % (tag, s.count(old)))
        return s, False
    print("  ok", tag)
    return s.replace(old, new), True


